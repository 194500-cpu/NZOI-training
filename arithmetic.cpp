#include <iostream>
#include <cmath>
using namespace std;

int main() {
	int a; int b;
	cin >> a >> b;
	cout << a << " + " << b << " = " << a + b << "\n";
	cout << a << " - " << b << " = " << a - b << "\n";
	cout << a << " x " << b << " = " << a * b << "\n";
	cout << a << " divided by " << b << " is " << a / b << " remainder " << a % b;
	return 0;
}
